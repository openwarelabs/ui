// Turns tokens/tokens.json (the single source of truth) into CSS:
//   src/styles/tokens.css   custom properties for both themes, the type-style classes
//   src/styles/tailwind.css an opt-in Tailwind v4 theme that maps utilities onto the tokens
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function buildTokens() {
    const tokens = JSON.parse(fs.readFileSync(path.join(root, "tokens/tokens.json"), "utf8"));

    const [firstTheme, ...otherThemes] = tokens.color.themes.map((theme) => theme.id);

    /** "{ow-gray-100}" → "var(--ow-gray-100)"; anything else as written. */
    const css = (value) => value.replace(/^\{([^}]+)\}$/, "var(--$1)");

    function valueFor(token, theme) {
        if (typeof token.value === "string") return theme === firstTheme ? token.value : undefined;
        return token.value[theme];
    }

    const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
    const plain = ["spacing", "radius", "timing", "weight"].flatMap((family) => tokens[family].tokens);

    const block = (selector, lines) => `${selector} {\n${lines.map((line) => `    ${line}`).join("\n")}\n}\n`;

    const themeLines = (theme) =>
        themed
            .map((token) => [token.name, valueFor(token, theme)])
            .filter(([, value]) => value !== undefined)
            .map(([name, value]) => `--${name}: ${css(value)};`);

    let out = `/* Generated from tokens/tokens.json by scripts/build-tokens.mjs. Don't edit by hand. */\n\n`;
    out += block(`:root,\n[data-theme="${firstTheme}"]`, [...themeLines(firstTheme), `color-scheme: ${firstTheme};`]);
    for (const theme of otherThemes) {
        out += "\n" + block(`[data-theme="${theme}"]`, [...themeLines(theme), `color-scheme: ${theme};`]);
        // data-theme="system" follows the operating system.
        out +=
            `\n@media (prefers-color-scheme: ${theme}) {\n` +
            block(`[data-theme="system"]`, [...themeLines(theme), `color-scheme: ${theme};`])
                .replace(/^/gm, "    ")
                .trimEnd() +
            "\n}\n";
    }

    const families = Object.entries(tokens.type.families).map(([key, stack]) => `--ow-font-${key}: ${stack};`);
    out += "\n" + block(":root", [...plain.map((token) => `--${token.name}: ${token.value};`), ...families]);

    // Type styles become classes of the same name: <p class="ow-type-lead">.
    for (const group of tokens.type.groups) {
        for (const style of group.styles) {
            const lines = [
                `font-family: var(--ow-font-${style.family ?? group.family});`,
                `font-size: ${style.fontSize};`,
                `line-height: ${style.lineHeight};`,
                `font-weight: ${style.fontWeight};`,
            ];
            if (style.letterSpacing) lines.push(`letter-spacing: ${style.letterSpacing};`);
            out += "\n" + block(`.${style.name}`, lines);
        }
    }

    fs.writeFileSync(path.join(root, "src/styles/tokens.css"), out);

    // Tailwind v4: `bg-surface`, `text-text-muted`, `rounded-container`, `p-lg`, `font-action`, `shadow-menu`…
    const strip = (name) => name.replace(/^ow-/, "");
    const tw = [
        ...tokens.color.tokens.map((t) => `--color-${strip(t.name)}: var(--${t.name});`),
        ...tokens.radius.tokens.map((t) => `--radius-${strip(t.name).replace(/^radius-/, "")}: var(--${t.name});`),
        ...tokens.spacing.tokens
            .filter((t) => t.name.startsWith("ow-space-"))
            .map((t) => `--spacing-${t.name.replace(/^ow-space-/, "")}: var(--${t.name});`),
        ...tokens.shadow.tokens.map((t) => `--shadow-${strip(t.name).replace(/^shadow-/, "")}: var(--${t.name});`),
        ...tokens.weight.tokens.map((t) => `--font-weight-${t.name.replace(/^ow-weight-/, "")}: var(--${t.name});`),
        ...Object.keys(tokens.type.families).map((key) => `--font-${key}: var(--ow-font-${key});`),
        `--ease-standard: var(--ow-ease-standard);`,
        `--ease-emphasized: var(--ow-ease-emphasized);`,
    ];
    fs.writeFileSync(
        path.join(root, "src/styles/tailwind.css"),
        `/* Generated by scripts/build-tokens.mjs. Opt-in Tailwind v4 theme: @import "@openwarelabs/ui/tailwind.css" after "tailwindcss". */\n\n` +
            `@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n\n` +
            block("@theme inline", tw),
    );

    return `tokens.css: ${themed.length} themed, ${plain.length} plain; tailwind.css: ${tw.length} mappings`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(buildTokens());
